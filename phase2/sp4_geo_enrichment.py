# GEOGRAPHIC SPOT CHECK
# ============================================================

def geographic_spot_check(
    grid_lookup_df
):

    print()
    print(
        "[13] Geographic spot-check..."
    )
    print("-" * 75)

    check_ids = [
        1,
        2,
        4821
    ]

    rows = (

        grid_lookup_df

        .filter(
            F.col(
                "grid_id"
            ).isin(
                check_ids
            )
        )

        .select(
            "grid_id",
            "geometry"
        )

        .orderBy(
            "grid_id"
        )

        .collect()
    )

    centroid_results = {}

    for row in rows:

        grid_id = row[
            "grid_id"
        ]

        geometry = json.loads(
            row[
                "geometry"
            ]
        )

        centroid = geometry_centroid(
            geometry
        )

        if centroid is None:

            print(
                f"Grid {grid_id}: "
                "centroid could not be calculated"
            )

            continue

        longitude, latitude = centroid

        centroid_results[
            grid_id
        ] = (
            longitude,
            latitude
        )

        print(
            f"grid_id={grid_id:4d} | "
            f"longitude={longitude:.6f} | "
            f"latitude={latitude:.6f}"
        )

    for grid_id in check_ids:

        if grid_id not in centroid_results:

            raise ValueError(
                "Could not calculate centroid "
                f"for grid_id {grid_id}"
            )

    # --------------------------------------------------------
    # Grid 1 vs Grid 2
    # --------------------------------------------------------

    lon1, lat1 = centroid_results[1]

    lon2, lat2 = centroid_results[2]

    distance = math.sqrt(

        (lon1 - lon2) ** 2

        +

        (lat1 - lat2) ** 2
    )

    print()

    print(
        f"Grid 1 -> Grid 2 centroid distance: "
        f"{distance:.8f}"
    )

    if distance <= 0:

        raise ValueError(
            "Grid 1 and Grid 2 have "
            "identical centroids."
        )

    print(
        "Grid 1 / Grid 2 adjacency sanity check: PASS"
    )

    # --------------------------------------------------------
    # Milan bounding box
    # --------------------------------------------------------

    lon4821, lat4821 = (
        centroid_results[4821]
    )

    in_milan_bbox = (

        8.8 <= lon4821 <= 9.6

        and

        45.2 <= lat4821 <= 45.8
    )

    print(
        f"Grid 4821 inside Milan bounding box: "
        f"{in_milan_bbox}"
    )

    if not in_milan_bbox:

        raise ValueError(
            "Grid 4821 centroid is outside "
            "the expected Milan bounding box."
        )

    print(
        "Geographic spot-check: PASS"
    )


