def write_sp3_output(df):

    print()
    print("[20] Writing SP3 output to Parquet...")
    print("-" * 75)

    print(
        "Output location:"
    )

    print(
        SP3_OUTPUT_DIR
    )

    # ------------------------------------------------------------------------
    # Remove previous SP3 output if it exists.
