# ENRICHMENT COVERAGE
# ============================================================

def validate_enrichment(
    activity_df,
    enriched_df
):

    print()
    print(
        "[11] Validating enrichment coverage..."
    )
    print("-" * 75)

    activity_grid_count = (

        activity_df

        .select(
            "grid_id"
        )

        .distinct()

        .count()
    )

    print(
        f"Distinct activity grids : "
        f"{activity_grid_count:,}"
    )

    matched_grids = (

        enriched_df

        .filter(
            F.col(
                "geometry"
            ).isNotNull()
        )

        .select(
            "grid_id"
        )

        .distinct()

        .count()
    )

    missing_grids = (

        enriched_df

        .filter(
            F.col(
                "geometry"
            ).isNull()
        )

        .select(
            "grid_id"
        )

        .distinct()
    )

    missing_grid_count = (
        missing_grids.count()
    )

    print(
        f"Matched grids            : "
        f"{matched_grids:,}"
    )

    print(
        f"Unmatched grids          : "
        f"{missing_grid_count:,}"
    )

    if activity_grid_count == 0:

        coverage = 0.0

    else:

        coverage = (

            matched_grids
            /
            activity_grid_count

        ) * 100

    print(
        f"Enrichment coverage      : "
        f"{coverage:.2f}%"
    )

    # --------------------------------------------------------
    # Unmatched IDs
    # --------------------------------------------------------

    print()
    print(
        "Unmatched grid_id values:"
    )

    print(
        "-" * 40
    )

    unmatched_ids = [

        row["grid_id"]

        for row in (

            missing_grids

            .orderBy(
                "grid_id"
            )

            .collect()
        )
    ]

    if unmatched_ids:

        print(
            unmatched_ids
        )

    else:

        print(
            "[]"
        )

    if coverage != 100.0:

        raise ValueError(
            f"Enrichment coverage is "
            f"{coverage:.2f}%. "
            "Expected 100%."
        )

    print()
    print(
        "Enrichment coverage: PASS"
    )

    print(
        "100% of observed grid_id values "
        "have geometry."
    )

    return unmatched_ids


