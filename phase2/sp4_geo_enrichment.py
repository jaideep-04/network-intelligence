# SP3 TEMPORAL VALIDATION
# ============================================================

def validate_sp3_temporal_coverage(df):

    print()
    print(
        "[5] Validating SP3 temporal coverage..."
    )
    print("-" * 75)

    distinct_dates = (

        df

        .select("date")

        .distinct()

        .count()
    )

    distinct_hours = (

        df

        .select("hour")

        .distinct()

        .count()
    )

    distinct_timestamps = (

        df

        .select("timestamp")

        .distinct()

        .count()
    )

    print(
        f"Distinct dates       : "
        f"{distinct_dates}"
    )

    print(
        f"Distinct hours       : "
        f"{distinct_hours}"
    )

    print(
        f"Distinct timestamps  : "
        f"{distinct_timestamps}"
    )

    # --------------------------------------------------------
    # SP3 should contain 7 days × 24 hours
    # --------------------------------------------------------

    expected_timestamps = 7 * 24

    if distinct_timestamps != expected_timestamps:

        raise ValueError(
            "SP3 temporal validation failed. "
            f"Expected {expected_timestamps} distinct "
            f"hourly timestamps but found "
            f"{distinct_timestamps}."
        )

    if distinct_dates != 7:

        raise ValueError(
            "SP3 temporal validation failed. "
            f"Expected 7 distinct dates but found "
            f"{distinct_dates}."
        )

    if distinct_hours != 24:

        raise ValueError(
            "SP3 temporal validation failed. "
            f"Expected 24 distinct hours but found "
            f"{distinct_hours}."
        )

    print()
    print(
        "Temporal coverage validation: PASS"
    )

    return distinct_timestamps


