# GEOJSON GRID ID RANGE VALIDATION
# ============================================================

def validate_grid_ids(
    grid_lookup_df
):

    print()
    print(
        "[8] Validating GeoJSON grid identifiers..."
    )
    print("-" * 75)

    result = (

        grid_lookup_df

        .agg(

            F.min(
                "grid_id"
            ).alias(
                "min_grid"
            ),

            F.max(
                "grid_id"
            ).alias(
                "max_grid"
            ),

            F.countDistinct(
                "grid_id"
            ).alias(
                "distinct_grid_ids"
            )
        )

        .first()
    )

    min_grid = result["min_grid"]
    max_grid = result["max_grid"]
    distinct_grid_ids = result[
        "distinct_grid_ids"
    ]

    print(
        f"Minimum grid_id       : "
        f"{min_grid}"
    )

    print(
        f"Maximum grid_id       : "
        f"{max_grid}"
    )

    print(
        f"Distinct grid IDs     : "
        f"{distinct_grid_ids:,}"
    )

    if (
        min_grid != 1
        or
        max_grid != EXPECTED_GRID_CELLS
        or
        distinct_grid_ids != EXPECTED_GRID_CELLS
    ):

        raise ValueError(
            "GeoJSON grid ID validation failed. "
            "Expected unique grid IDs 1-10000."
        )

    print(
        "Grid ID range validation: PASS"
    )


