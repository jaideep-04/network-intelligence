# POLYGON CENTROID
# ============================================================

def polygon_centroid(
    ring
):

    if not ring or len(ring) < 3:

        return None

    points = [

        (
            float(point[0]),
            float(point[1])
        )

        for point in ring

        if len(point) >= 2
    ]

    if len(points) < 3:

        return None

    if points[0] == points[-1]:

        points = points[:-1]

    if len(points) < 3:

        return None

    area_twice = 0.0

    cx = 0.0

    cy = 0.0

    n = len(points)

    for i in range(n):

        x1, y1 = points[i]

        x2, y2 = points[
            (i + 1) % n
        ]

        cross = (
            x1 * y2
            -
            x2 * y1
        )

        area_twice += cross

        cx += (
            x1 + x2
        ) * cross

        cy += (
            y1 + y2
        ) * cross

    if abs(area_twice) < 1e-12:

        avg_lon = (

            sum(
                p[0]
                for p in points
            )
            /
            len(points)
        )

        avg_lat = (

            sum(
                p[1]
                for p in points
            )
            /
            len(points)
        )

        return (
            avg_lon,
            avg_lat
        )

    cx /= (
        3.0 * area_twice
    )

    cy /= (
        3.0 * area_twice
    )

    return (
        cx,
        cy
    )


# ============================================================
# GEOMETRY CENTROID
# ============================================================

def geometry_centroid(
    geometry
):

    if not geometry:

        return None

    geometry_type = (
        geometry.get(
            "type"
        )
    )

    coordinates = (
        geometry.get(
            "coordinates"
        )
    )

    if not coordinates:

        return None

    # --------------------------------------------------------
    # Polygon
    # --------------------------------------------------------

    if geometry_type == "Polygon":

        outer_ring = coordinates[0]

        return polygon_centroid(
            outer_ring
        )

    # --------------------------------------------------------
    # MultiPolygon
    # --------------------------------------------------------

    if geometry_type == "MultiPolygon":

        centroids = []

        for polygon in coordinates:

            if not polygon:

                continue

            centroid = polygon_centroid(
                polygon[0]
            )

            if centroid:

                centroids.append(
                    centroid
                )

        if not centroids:

            return None

        lon = (

            sum(
                c[0]
                for c in centroids
            )
            /
            len(centroids)
        )

        lat = (

            sum(
                c[1]
                for c in centroids
            )
            /
            len(centroids)
        )

        return (
            lon,
            lat
        )

    return None


