# BUILD GRID LOOKUP
# ============================================================

def build_grid_lookup(
    spark,
    geojson
):

    print()
    print(
        "[7] Building Spark grid lookup..."
    )
    print("-" * 75)

    features = geojson.get(
        "features",
        []
    )

    if not features:

        raise ValueError(
            "GeoJSON contains no features."
        )

    # --------------------------------------------------------
    # Validate GeoJSON keys in Python
    # --------------------------------------------------------

    seen_ids = set()

    for feature in features:

        properties = feature.get(
            "properties",
            {}
        )

        cell_id = properties.get(
            "cellId"
        )

        if cell_id is None:

            raise ValueError(
                "Found GeoJSON feature without "
                "properties.cellId."
            )

        try:

            grid_id = int(
                cell_id
            )

        except (
            TypeError,
            ValueError
        ):

            raise ValueError(
                f"Invalid properties.cellId: "
                f"{cell_id}"
            )

        if grid_id in seen_ids:

            raise ValueError(
                f"Duplicate properties.cellId "
                f"found: {grid_id}"
            )

        seen_ids.add(
            grid_id
        )

        if feature.get(
            "geometry"
        ) is None:

            raise ValueError(
                f"Feature {grid_id} has no geometry."
            )

    print(
        f"Validated GeoJSON features: "
        f"{len(features):,}"
    )

    print(
        "Join key: properties.cellId"
    )

    # --------------------------------------------------------
    # Read GeoJSON directly through Spark
    # --------------------------------------------------------

    raw_geojson_df = (

        spark.read

        .option(
            "multiLine",
            "true"
        )

        .json(
            GEOJSON_PATH
        )
    )

    grid_lookup_df = (

        raw_geojson_df

        .select(
            F.explode(
                "features"
            ).alias(
                "feature"
            )
        )

        .select(

            F.col(
                "feature.properties.cellId"
            )
            .cast("long")
            .alias(
                "grid_id"
            ),

            F.to_json(
                F.col(
                    "feature.geometry"
                )
            )
            .alias(
                "geometry"
            )
        )

        .filter(

            F.col(
                "grid_id"
            ).isNotNull()

            &

            F.col(
                "geometry"
            ).isNotNull()
        )
    )

    lookup_count = (
        grid_lookup_df.count()
    )

    print(
        f"Grid lookup rows: "
        f"{lookup_count:,}"
    )

    print(
        f"Expected reference grid cells: "
        f"{EXPECTED_GRID_CELLS:,}"
    )

    if lookup_count != len(features):

        raise ValueError(
            "Grid lookup row count does not "
            "match GeoJSON feature count. "
            f"features={len(features):,}, "
            f"lookup={lookup_count:,}"
        )

    # --------------------------------------------------------
    # Duplicate grid IDs
    # --------------------------------------------------------

    duplicate_grid_ids = (

        grid_lookup_df

        .groupBy(
            "grid_id"
        )

        .count()

        .filter(
            F.col("count") > 1
        )

        .count()
    )

    print(
        f"Duplicate grid_id values in lookup: "
        f"{duplicate_grid_ids}"
    )

    if duplicate_grid_ids != 0:

        raise ValueError(
            "GeoJSON lookup contains duplicate "
            "grid_id values."
        )

    # --------------------------------------------------------
    # NULL grid IDs
    # --------------------------------------------------------

    null_grid_ids = (

        grid_lookup_df

        .filter(
            F.col("grid_id").isNull()
        )

        .count()
    )

    print(
        f"NULL grid_id values in lookup: "
        f"{null_grid_ids}"
    )

    if null_grid_ids != 0:

        raise ValueError(
            "GeoJSON lookup contains NULL grid_id values."
        )

    print(
        "Grid lookup validation: PASS"
    )

    return grid_lookup_df


