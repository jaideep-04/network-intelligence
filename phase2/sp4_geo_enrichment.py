def validate_sp3_parquet_exists():

    print()
    print("[2] Checking SP3 Parquet input...")
    print("-" * 75)

    if not os.path.exists(SP3_OUTPUT_DIR):

        raise FileNotFoundError(
            "SP3 Parquet output directory does not exist:\n"
            f"{SP3_OUTPUT_DIR}\n\n"
            "Run SP3 first."
        )

    parquet_files = []

    for root, dirs, files in os.walk(
        SP3_OUTPUT_DIR
    ):

        for filename in files:

            if filename.lower().endswith(
                ".parquet"
            ):

                parquet_files.append(
                    os.path.join(
                        root,
                        filename
                    )
                )

    if not parquet_files:

        raise FileNotFoundError(
            "No Parquet files found in SP3 output:\n"
            f"{SP3_OUTPUT_DIR}"
        )

    print(
        f"SP3 Parquet directory : "
        f"{SP3_OUTPUT_DIR}"
    )

    print(
        f"Parquet files found   : "
        f"{len(parquet_files)}"
    )

    for path in parquet_files[:10]:

        print(
            f"  - {os.path.basename(path)}"
        )

    if len(parquet_files) > 10:

        print(
            f"  ... and "
            f"{len(parquet_files) - 10} more"
        )

    print()
    print(
        "SP3 Parquet input: PASS"
    )

    return parquet_files


