# ============================================================================
# TEMPORAL VALIDATION
# ============================================================================
#
# IMPORTANT:
#
# The dataset has:
#
#   2013-11-01 05:30:00
#   through
#   2013-11-08 04:30:00
#
# This spans 8 calendar dates, but represents exactly:
#
#   7 days × 24 hours = 168 hourly timestamps
#
# Therefore we DO NOT require:
#
#   distinct_dates == 7
#
# Instead we validate:
#
#   1. 24 distinct hour values
#   2. 168 distinct timestamps
#   3. timestamps are exactly one hour apart
#
# ============================================================================

def validate_temporal_coverage(df):

    print()
    print("[14] Validating hourly timestamp coverage...")
    print("-" * 75)

    # ------------------------------------------------------------------------
    # DISTINCT TIMESTAMPS
    # ------------------------------------------------------------------------

    distinct_timestamps = (
        df
        .select("timestamp")
        .distinct()
        .count()
    )

    # ------------------------------------------------------------------------
    # DISTINCT DATES
    # ------------------------------------------------------------------------

    distinct_dates = (
        df
        .select("date")
        .distinct()
        .count()
    )

    # ------------------------------------------------------------------------
    # DISTINCT HOURS
    # ------------------------------------------------------------------------

    distinct_hours = (
        df
        .select("hour")
        .distinct()
        .count()
    )

    # ------------------------------------------------------------------------
    # MINIMUM / MAXIMUM TIMESTAMP
    # ------------------------------------------------------------------------

    timestamp_range = (
        df
        .select(
            F.min("timestamp").alias("min_timestamp"),
            F.max("timestamp").alias("max_timestamp")
        )
        .first()
    )

    min_timestamp = (
        timestamp_range["min_timestamp"]
    )

    max_timestamp = (
        timestamp_range["max_timestamp"]
    )

    # ------------------------------------------------------------------------
    # PRINT RESULTS
    # ------------------------------------------------------------------------

    print(
        f"Minimum timestamp        : "
        f"{min_timestamp}"
    )

    print(
        f"Maximum timestamp        : "
        f"{max_timestamp}"
    )

    print(
        f"Distinct calendar dates  : "
        f"{distinct_dates}"
    )

    print(
        f"Distinct hours           : "
        f"{distinct_hours}"
    )

    print(
        f"Distinct timestamps      : "
        f"{distinct_timestamps}"
    )

    print(
        f"Expected hourly timestamps: "
        f"{EXPECTED_HOURLY_TIMESTAMPS}"
    )

    # ------------------------------------------------------------------------
    # VALIDATE TIMESTAMP EXISTENCE
    # ------------------------------------------------------------------------

    if min_timestamp is None or max_timestamp is None:

        raise ValueError(
            "Timestamp validation failed. "
            "Minimum or maximum timestamp is NULL."
        )

    # ------------------------------------------------------------------------
    # VALIDATE 24 HOURS
    # ------------------------------------------------------------------------

    if distinct_hours != EXPECTED_HOURS_PER_DAY:

        raise ValueError(
            "Expected all 24 hours "
            f"but found {distinct_hours}."
        )

    # ------------------------------------------------------------------------
    # VALIDATE 168 HOURLY TIMESTAMPS
    # ------------------------------------------------------------------------

    if distinct_timestamps != EXPECTED_HOURLY_TIMESTAMPS:

        raise ValueError(
            "Expected "
            f"{EXPECTED_HOURLY_TIMESTAMPS} distinct hourly timestamps "
            f"but found {distinct_timestamps}."
        )

    # ------------------------------------------------------------------------
    # VALIDATE HOURLY INTERVALS
    #
    # IMPORTANT:
    #
    # We check distinct timestamps only.
    # Otherwise every grid would appear in the window calculation.
    # ------------------------------------------------------------------------

    window_spec = (
        Window
        .orderBy("timestamp")
    )

    timestamp_gaps = (

        df

        .select("timestamp")

        .distinct()

        .withColumn(
            "previous_timestamp",
            F.lag("timestamp").over(
                window_spec
            )
        )

        .withColumn(
            "diff_seconds",
            F.col("timestamp").cast("long")
            -
            F.col("previous_timestamp").cast("long")
        )

        .filter(
            F.col("previous_timestamp").isNotNull()
        )

        .filter(
            F.col("diff_seconds") != 3600
        )

        .count()
    )

    print(
        f"Non-hourly timestamp gaps : "
        f"{timestamp_gaps}"
    )

    if timestamp_gaps != 0:

        raise ValueError(
            "Timestamp coverage validation failed. "
            "Non-hourly timestamp gaps detected."
        )

    # ------------------------------------------------------------------------
    # PASS
    # ------------------------------------------------------------------------

    print()
    print(
        "Hourly timestamp count validation: PASS"
    )

    print(
        "24-hour coverage validation: PASS"
    )

    print(
        "Hourly interval validation: PASS"
    )

    print(
        "Temporal coverage validation: PASS"
    )


