def enrich_activity(
    activity_df,
    grid_lookup_df
):

    print()
    print(
        "[10] Performing geospatial enrichment..."
    )
    print("-" * 75)

    before_count = (
        activity_df.count()
    )

    print(
        f"Activity rows before join: "
        f"{before_count:,}"
    )

    print()
    print(
        "JOIN:"
    )

    print(
        "  activity.grid_id"
    )

    print(
        "      LEFT JOIN"
    )

    print(
        "  grid_lookup.grid_id"
    )

    grid_activity_geo_df = (

        activity_df

        .join(

            broadcast(
                grid_lookup_df
            ),

            on="grid_id",

            how="left"
        )
    )

    after_count = (
        grid_activity_geo_df.count()
    )

    print(
        f"Activity rows after join : "
        f"{after_count:,}"
    )

    if after_count != before_count:

        raise ValueError(
            "Row-count validation failed. "
            "The left join changed the row count. "
            "This indicates duplicate grid_id "
            "values in the lookup."
        )

    print(
        "Row-count preservation: PASS"
    )

    return grid_activity_geo_df


