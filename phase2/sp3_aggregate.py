def aggregate_country_codes(clean_df):

    print()
    print("[6] Aggregating country-code records...")
    print("-" * 75)

    print()
    print("SP3 transformation:")

    print(
        "BEFORE : timestamp + grid_id + country_code"
    )

    print(
        "AFTER  : timestamp + grid_id"
    )

    print()
    print("Aggregation rules:")

    print("  sms_in            -> SUM")
    print("  sms_out           -> SUM")
    print("  call_in           -> SUM")
    print("  call_out          -> SUM")
    print("  internet_activity -> SUM")

    print()
    print(
        "Executing groupBy(timestamp, grid_id)..."
    )

    # ------------------------------------------------------------------------
    # ACTUAL SP3 TRANSFORMATION
    # ------------------------------------------------------------------------

    hourly_grid_summary = (
        clean_df

        .groupBy(
            "timestamp",
            "grid_id"
        )

        .agg(

            F.round(
                F.sum("sms_in"),
                4
            ).alias("sms_in"),

            F.round(
                F.sum("sms_out"),
                4
            ).alias("sms_out"),

            F.round(
                F.sum("call_in"),
                4
            ).alias("call_in"),

            F.round(
                F.sum("call_out"),
                4
            ).alias("call_out"),

            F.round(
                F.sum("internet_activity"),
                4
            ).alias("internet_activity")
        )
    )

    return hourly_grid_summary


