# ============================================================
# VERIFY SP4 PARQUET
# ============================================================

def verify_sp4_output(
    spark,
    output_dir,
    expected_rows
):

    print()
    print(
        "[17] Verifying SP4 Parquet output..."
    )
    print("-" * 75)

    if not os.path.exists(
        output_dir
    ):

        raise FileNotFoundError(
            "SP4 Parquet output was not created:\n"
            f"{output_dir}"
        )

    parquet_files = []

    for root, dirs, files in os.walk(
        output_dir
    ):

        for filename in files:

            if filename.lower().endswith(
                ".parquet"
            ):

                parquet_files.append(
                    os.path.join(
                        root,
                        filename
                    )
                )

    print(
        f"Parquet files found: "
        f"{len(parquet_files)}"
    )

    if not parquet_files:

        raise ValueError(
            "No Parquet files found "
            "in SP4 output."
        )

    verified_df = (

        spark.read

        .parquet(
            output_dir
        )
    )

    actual_rows = (
        verified_df.count()
    )

    print(
        f"Rows read back from Parquet: "
        f"{actual_rows:,}"
    )

    if actual_rows != expected_rows:

        raise ValueError(
            "SP4 Parquet row-count "
            "verification failed. "
            f"Expected {expected_rows:,}, "
            f"found {actual_rows:,}."
        )

    # --------------------------------------------------------
    # Required schema
    # --------------------------------------------------------

    expected_columns = [

        "timestamp",
        "grid_id",

        "sms_in",
        "sms_out",

        "call_in",
        "call_out",

        "internet_activity",

        "total_activity",

        "geometry",
    ]

    if verified_df.columns != expected_columns:

        raise ValueError(
            "SP4 Parquet schema mismatch.\n"
            f"Expected: {expected_columns}\n"
            f"Found: {verified_df.columns}"
        )

    # --------------------------------------------------------
    # Geometry validation
    # --------------------------------------------------------

    null_geometry = (

        verified_df

        .filter(
            F.col(
                "geometry"
            ).isNull()
        )

        .count()
    )

    if null_geometry != 0:

        raise ValueError(
            "SP4 Parquet contains "
            "NULL geometry values."
        )

    print()
    print(
        "Verified SP4 Parquet schema:"
    )

    verified_df.printSchema()

    print()
    print(
        "SP4 Parquet verification: PASS"
    )

    return verified_df


