# ============================================================================
# HAND CHECK
# ============================================================================

def perform_hand_check(
    clean_df,
    hourly_grid_summary
):

    print()
    print(
        "[17] Hand-checking one grid and timestamp..."
    )
    print("-" * 75)

    sample_key = (

        clean_df

        .select(
            "grid_id",
            "timestamp"
        )

        .orderBy(
            "timestamp",
            "grid_id"
        )

        .first()
    )

    if sample_key is None:

        raise ValueError(
            "Unable to find sample "
            "grid/timestamp."
        )

    sample_grid = (
        sample_key["grid_id"]
    )

    sample_timestamp = (
        sample_key["timestamp"]
    )

    print(
        f"Selected grid_id  : "
        f"{sample_grid}"
    )

    print(
        f"Selected timestamp : "
        f"{sample_timestamp}"
    )

    # ------------------------------------------------------------------------
    # BEFORE SP3
    # ------------------------------------------------------------------------

    before = (

        clean_df

        .filter(

            (F.col("grid_id") == sample_grid)

            & (

                F.col("timestamp")
                == sample_timestamp
            )
        )

        .agg(

            F.sum("sms_in")
            .alias("sms_in"),

            F.sum("sms_out")
            .alias("sms_out"),

            F.sum("call_in")
            .alias("call_in"),

            F.sum("call_out")
            .alias("call_out"),

            F.sum(
                "internet_activity"
            )
            .alias("internet_activity")
        )

        .first()
    )

    # ------------------------------------------------------------------------
    # AFTER SP3
    # ------------------------------------------------------------------------

    after = (

        hourly_grid_summary

        .filter(

            (F.col("grid_id") == sample_grid)

            & (

                F.col("timestamp")
                == sample_timestamp
            )
        )

        .first()
    )

    if after is None:

        raise ValueError(
            "Hand-check failed. "
            "Aggregated record not found."
        )

    def rounded(value):

        if value is None:
            return 0.0

        return round(
            float(value),
            4
        )

    checks = [

        (
            "sms_in",
            rounded(
                before["sms_in"]
            ),
            rounded(
                after["sms_in"]
            )
        ),

        (
            "sms_out",
            rounded(
                before["sms_out"]
            ),
            rounded(
                after["sms_out"]
            )
        ),

        (
            "call_in",
            rounded(
                before["call_in"]
            ),
            rounded(
                after["call_in"]
            )
        ),

        (
            "call_out",
            rounded(
                before["call_out"]
            ),
            rounded(
                after["call_out"]
            )
        ),

        (
            "internet_activity",
            rounded(
                before["internet_activity"]
            ),
            rounded(
                after["internet_activity"]
            )
        ),
    ]

    print()
    print("Hand-check comparison:")

    hand_check_pass = True

    for (
        name,
        expected,
        actual
    ) in checks:

        passed = (
            expected == actual
        )

        print(
            f"  {name:<20} "
            f"expected={expected:<15} "
            f"actual={actual:<15} "
            f"{'PASS' if passed else 'FAIL'}"
        )

        if not passed:

            hand_check_pass = False

    if not hand_check_pass:

        raise ValueError(
            "Hand-check failed. "
            "SP3 aggregation does not match "
            "SP2 country-code sums."
        )

    print()
    print(
        "Hand-check: PASS"
    )


