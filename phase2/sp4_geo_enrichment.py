def validate_sp3_input(df):

    print()
    print(
        "[4] Validating SP3 input..."
    )
    print("-" * 75)

    # --------------------------------------------------------
    # Required columns
    # --------------------------------------------------------

    missing = [

        column

        for column in REQUIRED_SP3_COLUMNS

        if column not in df.columns
    ]

    if missing:

        raise ValueError(
            "SP3 is missing required columns:\n"
            + "\n".join(
                f"  - {column}"
                for column in missing
            )
        )

    print(
        "Required column validation: PASS"
    )

    # --------------------------------------------------------
    # Row count
    # --------------------------------------------------------

    row_count = df.count()

    print(
        f"SP3 rows received : "
        f"{row_count:,}"
    )

    if row_count == 0:

        raise ValueError(
            "SP3 contains zero rows."
        )

    # --------------------------------------------------------
    # Country code must already be removed by SP3
    # --------------------------------------------------------

    if "country_code" in df.columns:

        raise ValueError(
            "country_code must not exist "
            "in SP3 output."
        )

    print(
        "country_code removal validation: PASS"
    )

    # --------------------------------------------------------
    # SP3 grain
    # --------------------------------------------------------

    duplicate_count = (

        df

        .groupBy(
            "timestamp",
            "grid_id"
        )

        .count()

        .filter(
            F.col("count") > 1
        )

        .count()
    )

    print(
        f"Duplicate timestamp + grid_id groups : "
        f"{duplicate_count}"
    )

    if duplicate_count != 0:

        raise ValueError(
            "SP3 grain validation failed. "
            "Duplicate timestamp + grid_id "
            "groups detected."
        )

    print(
        "SP3 grain validation: PASS"
    )

    print(
        "SP3 grain = timestamp + grid_id"
    )

    return row_count


